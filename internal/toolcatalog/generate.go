//go:generate go run ../../cmd/gentools

// PluginTool is the subset of a catalog entry used by native plugins.
type PluginTool struct {
	Name        string          `json:"name"`
	Description string          `json:"description"`
	InputSchema json.RawMessage `json:"inputSchema"`
	Roles       []Role          `json:"roles"`
	Method      string          `json:"method"`
}

var pluginMethods = map[string]string{
	"agent_sessions_find": "sessions_find", "agent_session_get": "session_get",
	"agent_machines_find": "machines_find", "agent_machine_get": "machine_get",
	"agent_projects_find": "projects_find", "agent_workers_find": "list",
	"agent_messages_find": "messages", "agent_message_get": "message_status",
	"agent_graph_read": "agent_graph", "agent_settings_read": "settings_read", "agent_mcp_servers_find": "mcp_list",
	"agent_worker_profiles_find": "worker_profiles", "agent_message_send": "send",
	"agent_file_send":     "file_send",
	"agent_message_reply": "reply", "agent_announce": "announce",
	"agent_owner_ask": "waiting", "agent_learn": "agent_learn",
	"agent_worker_start": "worker_start", "agent_worker_stop": "worker_stop",
	"agent_worker_rate": "rate", "agent_handback": "worker_handback",
	"agent_project_add": "project_add", "agent_mcp_test": "mcp_test",
	"agent_change_submit": "change_submit", "agent_step_report": "step_report", "agent_changes_find": "changes_find",
}

// PluginTools returns the generated native-plugin view of the agent and worker
// roles. CTO-only tools are deliberately not exposed by these plugins.
func PluginTools() ([]PluginTool, error) {
	var out []PluginTool
	for _, tool := range Tools {
		var roles []Role
		for _, role := range tool.Roles {
			if role == RoleAgent || role == RoleWorker {
				roles = append(roles, role)
			}
		}
		if len(roles) == 0 {
			continue
		}
		method, ok := pluginMethods[tool.Name]
		if !ok {
			return nil, fmt.Errorf("tool %q has no plugin daemon method mapping", tool.Name)
		}
		out = append(out, PluginTool{Name: tool.Name, Description: tool.Description, InputSchema: tool.InputSchema, Roles: roles, Method: method})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// RenderPluginTools renders the checked-in TypeScript catalog used by both
// native plugins.
func RenderPluginTools() ([]byte, error) {
	tools, err := PluginTools()
	if err != nil {
		return nil, err
	}
	data, err := json.MarshalIndent(tools, "", "  ")
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go generate ./internal/toolcatalog; DO NOT EDIT.\n")
	out.WriteString("export const TOOL_CATALOG = ")
	out.Write(data)
	out.WriteString(" as const;\n")
	return out.Bytes(), nil
}

// GeneratePluginTools writes one generated catalog next to each plugin.
func GeneratePluginTools() error {
	data, err := RenderPluginTools()
	if err != nil {
		return err
	}
	for _, path := range []string{"../../plugins/pi/tools.gen.ts", "../../plugins/opencode/tools.gen.ts"} {
		if err := os.WriteFile(filepath.Clean(path), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
