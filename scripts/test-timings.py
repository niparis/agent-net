#!/usr/bin/env python3
"""Refresh shard weights: scripts/test-timings.py race-test-output*.json > scripts/test-timings.tsv.

Inputs are go test -race -json outputs from packages or named shards.
Subtests are already included in parents; later inputs replace earlier timings.
"""
import json
import sys

seconds = {}
for path in sys.argv[1:]:
    with open(path) as source:
        for line in source:
            event = json.loads(line)
            name = event.get("Test", "")
            if event["Action"] == "pass" and name and "/" not in name:
                package = event["Package"].rsplit("/", 1)[-1]
                seconds[package, name] = max(0.01, event["Elapsed"])

if not seconds:
    sys.exit("no top-level test timings found")
print("# Generated by scripts/test-timings.py from go test -race -json output.")
# A partial profile must not make every unmeasured integration test look
# cheaper than the measured ones. New tests inherit their package mean.
packages = {}
for (package, _), duration in seconds.items():
    packages.setdefault(package, []).append(duration)
for package, durations in packages.items():
    seconds[package, "*"] = sum(durations) / len(durations)
print("# Package Test Seconds (* is the default for unmeasured tests).")
for (package, name), duration in sorted(seconds.items()):
    print(f"{package}\t{name}\t{duration:.2f}")
